import Foundation
import KKitServicesAPI

/// What Clipboard History keeps (Settings › Clipboard).
struct ClipboardRules: Sendable, Equatable {
    var ignoredBundleIDs: Set<String> = ClipboardFilter.defaultIgnoredApps
    var keepsRichText = true
    var keepsImages = true
    var keepsFiles = true
    /// Bigger images aren't saved.
    var maxImageBytes = 25 * 1024 * 1024
    /// Longer text isn't saved.
    var maxTextLength = 500_000
}

/// Decides whether a clipboard change is saved, and as what. Pure, so it's tested
/// without a clipboard.
enum ClipboardFilter {
    /// Types apps put on the clipboard to say "don't record this" (nspasteboard.org),
    /// plus a few password managers' own markers.
    static let privacyMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Password managers, ignored by default.
    static let defaultIgnoredApps: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop",
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.lastpass.LastPass",
        "com.dashlane.dashlanephonefinal",
        "org.keepassxc.keepassxc",
        "in.sinew.Enpass-Desktop",
        "me.proton.pass.electron",
    ]

    static func draft(from change: PasteboardChange, rules: ClipboardRules) -> ClipboardDraft? {
        let contents = change.contents
        guard Set(contents.types).isDisjoint(with: privacyMarkers) else { return nil }
        if let source = change.sourceBundleID, rules.ignoredBundleIDs.contains(source) {
            return nil
        }
        var draft = ClipboardDraft(
            kind: .text,
            text: "",
            sourceBundleID: change.sourceBundleID,
            sourceAppName: change.sourceAppName,
            date: change.date
        )

        if !contents.fileURLs.isEmpty {
            guard rules.keepsFiles else { return nil }
            draft.kind = .files
            draft.fileURLs = contents.fileURLs
            draft.text = contents.fileURLs.map(\.path).joined(separator: "\n")
            return draft
        }

        if let image = contents.image, contents.string?.isEmpty ?? true {
            guard rules.keepsImages, image.count <= rules.maxImageBytes else { return nil }
            draft.kind = .image
            draft.imageData = image
            draft.imageType = contents.imageType ?? "public.tiff"
            return draft
        }

        if let color = contents.color, contents.string.map({ RGBAColor(hex: $0) != nil }) ?? true {
            draft.kind = .color
            draft.color = color
            draft.text = color.hex
            return draft
        }

        guard let string = contents.string ?? contents.url?.absoluteString else { return nil }
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, string.count <= rules.maxTextLength else { return nil }
        draft.text = string

        if let color = RGBAColor(hex: trimmed), trimmed.hasPrefix("#") {
            draft.kind = .color
            draft.color = color
            draft.text = trimmed
        } else if isLink(trimmed) {
            draft.kind = .link
            draft.text = trimmed
        } else if rules.keepsRichText, let rtf = contents.rtf {
            draft.kind = .richText
            draft.rtf = rtf
        }
        return draft
    }

    /// A single web or mail link, nothing else.
    static func isLink(_ text: String) -> Bool {
        guard !text.contains(where: \.isWhitespace), let url = URL(string: text), let scheme = url.scheme?.lowercased() else {
            return false
        }
        switch scheme {
        case "http", "https":
            return url.host() != nil
        case "mailto", "tel", "obsidian", "x-apple.systempreferences":
            return true
        default:
            return false
        }
    }
}
